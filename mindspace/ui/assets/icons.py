def render_svg_pixmap(name: str, color: str = "#858585", fill: str = "none", size: int = 18) -> QPixmap:
    """Renders an SVG string into a high-DPI QPixmap."""
    raw_svg = SVG_ICONS.get(name, SVG_ICONS["notes"])
    svg_content = raw_svg.format(color=color, fill=fill)

    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return pixmap


def get_icon(name: str, color: str = "#858585", fill: str = "none", size: int = 18) -> QIcon:
    """Returns a QIcon for a given icon name."""
    pixmap = render_svg_pixmap(name, color=color, fill=fill, size=size)
    return QIcon(pixmap)

